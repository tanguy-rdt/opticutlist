import { mount } from '@vue/test-utils'
import { afterEach, describe, expect, it } from 'vitest'
import AppSplitButton from '@/ui/components/common/AppSplitButton.vue'

const props = { label: 'New project', menuLabel: 'More project actions', actions: [{ value: 'import', label: 'Import project' }] }
const wrappers: ReturnType<typeof mount>[] = []
function render() { const wrapper = mount(AppSplitButton, { props, attachTo: document.body }); wrappers.push(wrapper); return wrapper }
afterEach(() => { for (const wrapper of wrappers) wrapper.unmount(); wrappers.length = 0 })
describe('shared split button', () => {
  it('uses connected primary shared buttons with independent click targets', async () => {
    const wrapper = render()
    const controls = wrapper.findAll('button')
    expect(controls).toHaveLength(2)
    expect(controls.every(control => control.classes().includes('button-primary'))).toBe(true)
    expect(controls.every(control => !control.classes().includes('button-compact'))).toBe(true)
    expect(controls[0]?.text()).toBe('New project')
    const trigger = wrapper.get('button[aria-haspopup="menu"]')
    expect(trigger.attributes('aria-label')).toBe('More project actions')
    await trigger.trigger('click')
    expect(wrapper.emitted('primary')).toBeUndefined()
    expect(trigger.attributes('aria-controls')).toBe(wrapper.get('[role="menu"]').attributes('id'))
    expect(wrapper.get('[role="menu"]').classes()).toEqual(expect.arrayContaining(['top-full', 'right-0']))
    await wrapper.get('[role="menuitem"]').trigger('click')
    expect(wrapper.emitted('select')).toEqual([['import']])
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    expect(document.activeElement).toBe(trigger.element)
    await trigger.trigger('click')
    await controls[0]?.trigger('click')
    expect(wrapper.emitted('primary')).toEqual([[]])
    expect(wrapper.emitted('select')).toHaveLength(1)
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
  })
  it('supports arrow keys, Home/End and Escape with focus restoration', async () => {
    const wrapper = render()
    await wrapper.setProps({ actions: [...props.actions, { value: 'other', label: 'Other action' }] })
    const trigger = wrapper.get('button[aria-haspopup="menu"]')
    await trigger.trigger('keydown', { key: 'ArrowDown' })
    const items = wrapper.findAll('[role="menuitem"]')
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'ArrowDown' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'ArrowDown' })
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'ArrowUp' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'Home' })
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'End' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'Escape' })
    expect(trigger.attributes('aria-expanded')).toBe('false')
    expect(document.activeElement).toBe(trigger.element)
    await trigger.trigger('keydown', { key: 'ArrowUp' })
    expect(document.activeElement).toBe(wrapper.findAll('[role="menuitem"]')[1]?.element)
  })
  it('dismisses on outside pointer and when keyboard focus leaves', async () => {
    const wrapper = render()
    const trigger = wrapper.get('button[aria-haspopup="menu"]')
    await trigger.trigger('click')
    document.body.dispatchEvent(new Event('pointerdown', { bubbles: true }))
    await wrapper.vm.$nextTick()
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    await trigger.trigger('click')
    const outside = document.createElement('button'); document.body.append(outside); outside.focus()
    await wrapper.vm.$nextTick()
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    outside.remove()
  })
  it('keeps secondary actions available when the primary action is disabled', async () => {
    const wrapper = render()
    await wrapper.setProps({ primaryDisabled: true })
    expect(wrapper.findAll('button')[0]?.attributes('disabled')).toBeDefined()
    await wrapper.findAll('button')[0]?.trigger('click')
    expect(wrapper.emitted('primary')).toBeUndefined()
    await wrapper.get('button[aria-haspopup="menu"]').trigger('click')
    expect(wrapper.find('[role="menu"]').exists()).toBe(true)
    await wrapper.setProps({ actions: [] })
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    expect(wrapper.get('button[aria-haspopup="menu"]').attributes('disabled')).toBeDefined()
  })
})
