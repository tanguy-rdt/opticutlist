import { mount } from '@vue/test-utils'
import { afterEach, describe, expect, it } from 'vitest'
import SupplierActions from '../SupplierActions.vue'

function render(disabled = false) { return mount(SupplierActions, { props: { disabled }, attachTo: document.body }) }
afterEach(() => { document.body.replaceChildren() })
describe('supplier actions menu', () => {
  it('opens below/right of a compact accessible shared button and closes on actions', async () => {
    const wrapper = render()
    const trigger = wrapper.get('button')
    expect(trigger.attributes('aria-label')).toBe('Supplier actions')
    expect(trigger.attributes('aria-haspopup')).toBe('menu')
    expect(trigger.classes()).toContain('button-compact')
    expect(trigger.classes()).toContain('button-icon')
    for (const [index, action] of ['edit', 'delete'].entries()) {
      await trigger.trigger('click')
      const menu = wrapper.get('[role="menu"]')
      expect(menu.classes()).toEqual(expect.arrayContaining(['right-0', 'top-full']))
      expect(trigger.attributes('aria-controls')).toBe(menu.attributes('id'))
      expect(menu.findAll('button').map(item => item.text())).toEqual(['Edit supplier', 'Delete supplier'])
      await menu.findAll('button')[index]?.trigger('click')
      expect(wrapper.emitted(action)).toHaveLength(1)
      expect(wrapper.find('[role="menu"]').exists()).toBe(false)
      expect(document.activeElement).toBe(trigger.element)
    }
    wrapper.unmount()
  })
  it('supports arrow navigation, Home, End, Escape and opening upwards', async () => {
    const wrapper = render()
    const trigger = wrapper.get('button')
    await trigger.trigger('keydown', { key: 'ArrowDown' })
    const items = wrapper.findAll('[role="menuitem"]')
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'ArrowDown' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'ArrowDown' })
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'ArrowUp' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'Home' })
    expect(document.activeElement).toBe(items[0]?.element)
    await items[0]?.trigger('keydown', { key: 'End' })
    expect(document.activeElement).toBe(items[1]?.element)
    await items[1]?.trigger('keydown', { key: 'Escape' })
    expect(trigger.attributes('aria-expanded')).toBe('false')
    expect(document.activeElement).toBe(trigger.element)
    await trigger.trigger('keydown', { key: 'ArrowUp' })
    expect(document.activeElement).toBe(wrapper.findAll('[role="menuitem"]')[1]?.element)
    wrapper.unmount()
  })
  it('closes for an outside click or keyboard focus leaving the group', async () => {
    const wrapper = render()
    const trigger = wrapper.get('button')
    await trigger.trigger('click')
    document.body.dispatchEvent(new Event('pointerdown', { bubbles: true }))
    await wrapper.vm.$nextTick()
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    await trigger.trigger('click')
    const outside = document.createElement('button'); document.body.append(outside); outside.focus()
    await wrapper.vm.$nextTick()
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    wrapper.unmount()
  })
  it('blocks disabled actions and closes an open menu when disabled', async () => {
    const wrapper = render(true)
    await wrapper.get('button').trigger('click')
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    await wrapper.setProps({ disabled: false }); await wrapper.get('button').trigger('click')
    await wrapper.setProps({ disabled: true })
    expect(wrapper.find('[role="menu"]').exists()).toBe(false)
    expect(wrapper.get('button').attributes('disabled')).toBeDefined()
    wrapper.unmount()
  })
})
